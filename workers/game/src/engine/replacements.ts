export type ReplacementEvent =
  | "WOULD_BE_KO"
  | "WOULD_BE_REMOVED_FROM_FIELD"
  | "WOULD_LEAVE_FIELD"
  | "WOULD_BE_RESTED"
  | "WOULD_LOSE_GAME"
  | "LIFE_ADDED_TO_HAND";

export interface ReplacementResult {
  replaced: boolean;
  state: GameState;
  /** If replaced, the substitute action to execute instead */
  substituteAction?: GameAction;
  /** Events generated by the replacement itself */
  events: PendingEvent[];
}

/** An optional replacement offer awaiting its REPLACEMENT frame (OPT-963); never persisted. */
export interface ReplacementScanProgress {
  visitedEffectIds?: string[];
  cause?: "battle" | "effect";
  causingController?: 0 | 1;
  orderingEffectIds?: string[];
}

export interface ReplacementOffer extends ReplacementScanProgress {
  effectId: string;
  targetInstanceId: string;
  event: ReplacementEvent;
}

export interface ReplacementCheckResult {
  /** Set with `pendingPrompt` when the prompt is an optional replacement offer. */
  offer?: ReplacementOffer;
  /** A matching replacement was found and applied (non-optional) */
  replaced: boolean;
  state: GameState;
  events: PendingEvent[];
  /** If the replacement is optional, a prompt to send to the player */
  pendingPrompt?: PendingPromptState;
}

interface ReplacementParams {
  trigger: string;
  cause_filter?: CauseFilter | null;
  target_filter?: TargetFilter | null;
  replacement_actions: Action[];
  optional: boolean;
  once_per_turn: boolean;
  usedOnTurn?: number;
}

const REPLACEMENT_EVENTS = new Set<string>([
  "WOULD_BE_KO",
  "WOULD_BE_REMOVED_FROM_FIELD",
  "WOULD_LEAVE_FIELD",
  "WOULD_BE_RESTED",
  "WOULD_LOSE_GAME",
  "LIFE_ADDED_TO_HAND",
]);
const REPLACEMENT_ACTION_TYPES = new Set<string>(ALL_ACTION_TYPES);

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isReplacementAction(value: unknown): value is Action {
  if (
    !isRecord(value) ||
    typeof value.type !== "string" ||
    !REPLACEMENT_ACTION_TYPES.has(value.type)
  )
    return false;
  if (!isRecord(value.params)) return value.params === undefined;
  if (value.type === "PLAYER_CHOICE" || value.type === "OPPONENT_CHOICE") {
    return (
      Array.isArray(value.params.options) &&
      value.params.options.every(
        (branch) => Array.isArray(branch) && branch.every(isReplacementAction)
      )
    );
  }
  if (value.type === "OPPONENT_ACTION" || value.type === "SCHEDULE_ACTION") {
    return isReplacementAction(value.params.action);
  }
  return true;
}

const CAUSE_FILTER_BY = new Set<string>(ALL_CAUSE_FILTER_BY);

function isCauseFilter(value: unknown): value is CauseFilter {
  return (
    isRecord(value) && typeof value.by === "string" && CAUSE_FILTER_BY.has(value.by)
  );
}

function isTargetFilter(value: unknown): value is TargetFilter {
  return isRecord(value);
}

function isReplacementParams(value: unknown): value is ReplacementParams {
  if (
    !isRecord(value) ||
    typeof value.trigger !== "string" ||
    !REPLACEMENT_EVENTS.has(value.trigger) ||
    typeof value.optional !== "boolean" ||
    typeof value.once_per_turn !== "boolean" ||
    !Array.isArray(value.replacement_actions) ||
    !value.replacement_actions.every(isReplacementAction)
  )
    return false;
  return (
    (value.cause_filter == null || isCauseFilter(value.cause_filter)) &&
    (value.target_filter == null || isTargetFilter(value.target_filter))
  );
}

